    fn lookup_by_cpid_bdid() {
        // iPhone 11 (A13, n104ap): CPID 0x8030, BDID 0x04.
        let dev = by_cpid_bdid(0x8030, 0x04).expect("iPhone 11 must be in the table");
        assert_eq!(dev.product_type, "iPhone12,1");
        assert_eq!(dev.hardware_model, "n104ap");
        assert_eq!(dev.display_name, "iPhone 11");
    }

    #[test]
    fn lookup_by_product_type_case_insensitive() {
        let dev = by_product_type("iphone12,1").expect("lookup should be case-insensitive");
        assert_eq!(dev.hardware_model, "n104ap");
    }

    #[test]
    fn lookup_by_hardware_model() {
        let dev = by_hardware_model("D22AP").expect("lookup should be case-insensitive");
        assert_eq!(dev.product_type, "iPhone10,3");
        assert_eq!(dev.display_name, "iPhone X (Global)");
    }

    #[test]
    fn duplicate_product_type_returns_first_match() {
        // iPhone8,1 appears twice (n71ap at CPID 0x8000, n71map at CPID
        // 0x8003) — a product_type lookup returns the first table entry,
        // matching libirecovery's own sequential-scan-then-break behavior.
        let dev = by_product_type("iPhone8,1").unwrap();
        assert_eq!(dev.hardware_model, "n71ap");
    }

    #[test]
    fn unknown_lookup_returns_none() {
        assert!(by_cpid_bdid(0xFFFF, 0xFF).is_none());
        assert!(by_product_type("iPhoneNotReal,1").is_none());
        assert!(by_hardware_model("notreal").is_none());
    }
