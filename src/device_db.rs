//! Device database — a near-verbatim port of the `irecv_devices[]` table
//! from `libirecovery/src/libirecovery.c` (318 entries), plus the
//! `irecv_devices_get_device_by_{product_type,hardware_model,...}` lookup
//! functions. Pure static data, no I/O — works on any target.
//!
//! Because this table is copied from libirecovery (LGPL-2.1-only), this
//! crate is licensed the same way — see `LICENSE` and `NOTICE.md` in the
//! repository root.

/// Mirrors `struct irecv_device` (libirecovery.h). `product_type` /
/// `hardware_model` are the device's identifiers (e.g. `"iPhone12,1"` /
/// `"n104ap"`); `chip_id` / `board_id` are the lookup key read from the
/// `CPID:`/`BDID:` tags in the iBoot serial string (see
/// [`crate::info::DeviceInfo`]).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct IrecvDevice {
    pub product_type: &'static str,
    pub hardware_model: &'static str,
    pub board_id: u32,
    pub chip_id: u32,
    pub display_name: &'static str,
}

const fn d(
    product_type: &'static str,
    hardware_model: &'static str,
    board_id: u32,
    chip_id: u32,
    display_name: &'static str,
) -> IrecvDevice {
    IrecvDevice {
        product_type,
        hardware_model,
        board_id,
        chip_id,
        display_name,
    }
}

