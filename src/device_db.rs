/// Ports `irecv_devices_get_device_by_client`: look up by the `(CPID,
/// BDID)` pair read from the iBoot serial string. This is the same
/// approach libirecovery itself uses in `irecv_get_device()` — matching by
/// hardware model first isn't done here since that needs an SRTG "hw
/// model" field many serial strings don't include.
pub fn by_cpid_bdid(chip_id: u32, board_id: u32) -> Option<&'static IrecvDevice> {
    DEVICES
        .iter()
        .find(|dev| dev.chip_id == chip_id && dev.board_id == board_id)
}

/// Ports `irecv_devices_get_device_by_product_type`. Case-insensitive, to
/// stay forgiving of hand-typed or telemetry-sourced input.
pub fn by_product_type(product_type: &str) -> Option<&'static IrecvDevice> {
    DEVICES
        .iter()
        .find(|dev| dev.product_type.eq_ignore_ascii_case(product_type))
}

/// Ports `irecv_devices_get_device_by_hardware_model`. Case-insensitive.
pub fn by_hardware_model(hardware_model: &str) -> Option<&'static IrecvDevice> {
    DEVICES
        .iter()
        .find(|dev| dev.hardware_model.eq_ignore_ascii_case(hardware_model))
}

